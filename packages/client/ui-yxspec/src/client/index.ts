/**
 * Required client services: the Remote carrier, the two mounted namespaces, the slot registry,
 * the Workspace Controller's commands, the Session list, and copy.
 *
 * `remote.yxspec` and `remote.yxspecRemote` are service keys in their own right, not plain
 * properties of `remote`: the Gateway installs each namespace as a separate
 * `remote.<namespace>` service. Cordis only lets a plugin read a service it declared, so
 * naming them here is what the reads depend on. Omitting one does not fail loudly at load —
 * the read throws `cannot get property "remote.x" without inject`, which inside the surface's
 * own loader collapses into the same "unavailable" branch as a genuinely unmounted host, and
 * the surface would quietly report a missing service while the host is healthy.
 */
export const inject = [
  'remote', 'remote.yxspec', 'remote.yxspecRemote', 'remote.directoryPicker',
  'slots', 'locale', 'workspaces', 'sessions', 'uiWorkspace',
]

const NS = 'yxspec'

/**
 * Key under which onboarding progress persists. The store is keyed by project inside, so one
 * key holds every project's record; two stores sharing this key would cross-contaminate.
 */
const ONBOARDING_STORE = 'yxspec-onboarding'

/**
 * Key under which the project this walk of the wizard is onboarding persists.
 *
 * A separate key rather than a field of the record above, because that record is keyed by the
 * very id this one holds: a rootless project would have to exist inside its own key before it
 * could be written under it.
 */
const ONBOARDING_TARGET_STORE = 'yxspec-onboarding-target'

/**
 * Key under which a walk asked for from outside the wizard persists.
 *
 * Persisted although it is transient, and deliberately: the gesture arrives at the sidebar while
 * the operator is *not* on a home, so the request has to survive the navigation to the blank home
 * that acts on it — and that navigation may be a reload. Clearing it is what step 1 does.
 */
const ONBOARDING_REQUEST_STORE = 'yxspec-onboarding-request'


/** The generated carrier's result envelope: a value, or the failure the host reported. */
interface RemoteOutcome<T> {
  readonly ok: boolean
  readonly value?: T
  readonly error?: { readonly message: string }
}

/**
 * Install the section's copy, its session-panel section, and the onboarding gate.
 *
 * The two registrations are independent: a deployment that mounts this package always gets
 * both, because the gate is what makes the section's process model meaningful.
 * @param ctx - client root context.
 */
export function apply(ctx: ClientContext): void {
  ctx.effect(() => ctx.locale.register(NS, { zh, en, ja, es, fr, de, ru, pt }), 'ui-yxspec: dictionaries')

  // Bound once and handed to both surfaces: the panel section shows a server's state and the wizard
  // declares and tests one, and two copies of these two calls could drift apart at the wire.
  const loadServers = loadServersFor(ctx)
  const probeServer = probeServerFor(ctx)

  const load = async (landedStages?: string[]): Promise<YxspecStatusValue | undefined> => {
    const namespace = ctx.remote.yxspec
    if (namespace === undefined) return undefined
    const result = await namespace.status(landedStages) as RemoteOutcome<YxspecStatusValue>
    return result.ok ? result.value : undefined
  }

  ctx.slots.inject('conversation.session.panel.section', () => ctx.slots.register({
    name: 'conversation.session.panel.section',
    id: 'yxspec',
    order: 20,
    label: () => ctx.locale.bind(NS)('section.title'),
    locale: NS,
    inject: (): YxspecSectionInjected => ({ load, loadServers, probeServer }),
  }, YxspecSection))

  registerOnboarding(ctx)
}

/**
 * Read the build servers one project declared.
 *
 * Both surfaces that show a server — the Session panel's section and the wizard's server step —
 * read through this, so a deployment without the `yxspecRemote` namespace shows no servers in
 * either place rather than one place disagreeing with the other.
 * @param workspaceId - the project whose declarations to read.
 * @returns the declarations; empty when the namespace is absent or the project declared none.
 */
const loadServersFor = (ctx: ClientContext) =>
  async (workspaceId: string): Promise<YxspecRemoteServerView[]> => {
    const namespace = ctx.remote.yxspecRemote
    if (namespace === undefined) return []
    const result = await namespace.servers(workspaceId) as RemoteOutcome<YxspecRemoteServerView[]>
    return result.ok ? result.value ?? [] : []
  }

/**
 * Test one declared build server.
 *
 * A host that does not answer is an answer: the outcome comes back rather than throwing, and the
 * host stores it on the declaration, so both surfaces re-read their list instead of holding state
 * of their own. Only a refused call throws — an unknown server, or a deployment that mounts no
 * build-server service.
 * @param ctx - the client root context.
 * @returns the probe binding both surfaces use.
 */
const probeServerFor = (ctx: ClientContext) =>
  async (workspaceId: string, serverId: string): Promise<YxspecRemoteProbe> => {
    const namespace = ctx.remote.yxspecRemote
    if (namespace === undefined) throw new Error('the build-server namespace is not mounted')
    const result = await namespace.probeServer(workspaceId, serverId) as RemoteOutcome<YxspecRemoteProbe>
    if (!result.ok || result.value === undefined) {
      throw new Error(result.error?.message ?? 'the probe was refused')
    }
    return result.value
  }

/**
 * Register the onboarding gate over the hero frame.
 *
 * The wizard resolves the project it gates from the standard `useSessions`/`useWorkspaces` kit
 * at render time rather than from a prop: the frame's owner share belongs to the conversation
 * package, and widening it would make every other layer's props depend on this one's needs.
 * @param ctx - client root context.
 */
function registerOnboarding(ctx: ClientContext): void {
  // Progress is keyed by project inside the record: two projects in one browser have different
  // specifications and different servers, so a global flag would gate the second on the first.
  const store: SnapshotStore<OnboardingState> = createSnapshotStore<OnboardingState>(
    {}, { persist: { name: ONBOARDING_STORE } },
  )
  // Which project this walk created. Its own slot, not a progress field: the record is keyed by
  // this id, so a project with no roots would have to exist inside its own key before being
  // written under it.
  const target: SnapshotStore<OnboardingTarget> = createSnapshotStore<OnboardingTarget>(
    EMPTY_TARGET, { persist: { name: ONBOARDING_TARGET_STORE } },
  )
  // A walk asked for from outside the wizard. Its own slot rather than a progress field for the
  // same reason the target has one: it is a request about a walk that has no project yet.
  const request: SnapshotStore<OnboardingRequest> = createSnapshotStore<OnboardingRequest>(
    EMPTY_REQUEST, { persist: { name: ONBOARDING_REQUEST_STORE } },
  )

  /**
   * Show the guided creation, and land where the wizard can act on it.
   *
   * The blank home is the *only* place the gate takes over — it rides the hero frame — so a
   * gesture raised from the sidebar while a Session is open has to move there first, or the
   * request would sit unread until the operator happened to close what they were looking at.
   *
   * Order matters. The request is written before the navigation: the navigation re-renders the
   * wizard, and a walk that arrived at the home *after* reading the request would open one frame
   * late on whatever the gate had already resolved.
   * @param fresh - true to start a new walk, false to resume the resolved project's.
   */
  const openGuidedCreation = (fresh: boolean): void => {
    request.set(fresh ? { starting: true } : EMPTY_REQUEST)
    ctx.uiWorkspace.openHome()
  }
  // Registered as an optional service, not injected by the workspace surfaces' hard list: it
  // replaces an affordance they already have, so a deployment without this plugin keeps the
  // directory flow and must not fail to load.
  provideProjectOnboarding(ctx, {
    open: openGuidedCreation,
    cancel: () => {
      // Cleared, not navigated: the caller is *already* on its way somewhere (this answers a
      // navigation gesture), so moving the view again would fight it. Writing the shared constant
      // is a no-op for a store that already holds it, which is what makes "no request
      // outstanding" free rather than a re-render on every navigation.
      request.set(EMPTY_REQUEST)
    },
  }, () => store.getSnapshot())

  const saveProgress = (projectId: string | undefined, progress: OnboardingProgress): void => {
    if (projectId === undefined) return
    // A whole-record write rather than a draft mutation: the stored shape is `Readonly`
    // (consumers only ever read one project's slice), so the keyed write happens here
    // where the identifier is resolved. Persistence rides the same setState path.
    store.set({ ...store.getSnapshot(), [projectId]: progress })
  }

  /**
   * Name the project this walk is about, creating it when the walk has none yet.
   *
   * The whole reason this lives here rather than in the component: a create answers with an id
   * the component has never rendered with, and both the progress record (keyed by project) and
   * the walk's own target want to be written under it. Doing that at the injection layer means
   * the id goes straight from the create response into both writes, with no round trip through
   * a catalogue that has not caught up.
   *
   * A rootless project has no path for `create` to match on, so this cannot be "create always,
   * let the host dedupe": a second walk over a recorded project would silently make a second
   * one. Hence the branch — rename what exists, create what does not.
   * @param projectId - the project this walk resolved, or undefined before it has one.
   * @param title - the operator's name for the project.
   */
  /**
   * Test one declared build server.
   *
   * A host that does not answer is an answer: the outcome comes back rather than throwing, and the
   * host stores it on the declaration, so the step re-reads the row instead of holding state of its
   * own. Only a refused call throws — an unknown server, or a deployment that mounts no
   * build-server service — because those are the cases the operator has to act on.
   * @param workspaceId - the project that declared the server.
   * @param serverId - the declaration to test.
   * @returns what the probe concluded.
   */
  const probeServer = async (workspaceId: string, serverId: string): Promise<YxspecRemoteProbe> => {
    const namespace = ctx.remote.yxspecRemote
    if (namespace === undefined) throw new Error('the build-server namespace is not mounted')
    const result = await namespace.probeServer(workspaceId, serverId) as RemoteOutcome<YxspecRemoteProbe>
    if (!result.ok || result.value === undefined) {
      throw new Error(result.error?.message ?? 'the probe was refused')
    }
    return result.value
  }

  /**
   * List the directories under one path on a server, for the wizard's picker.
   *
   * The only call this half makes that names a destination instead of a declaration, because it runs
   * before the declaration exists: the operator connects, chooses, and what they chose is declared.
   * A host that cannot answer is answered inside the listing — an unreachable machine, a missing
   * path, and an empty directory are three states the picker renders differently.
   * @param request - the destination to reach and the directory to list.
   * @returns the listing, with `error` set when it could not be produced.
   */
  const browseServer = async (request: YxspecRemoteBrowseRequest): Promise<YxspecRemoteBrowse> => {
    const namespace = ctx.remote.yxspecRemote
    if (namespace === undefined) throw new Error('the build-server namespace is not mounted')
    const result = await namespace.browseServer(request) as RemoteOutcome<YxspecRemoteBrowse>
    if (!result.ok || result.value === undefined) {
      throw new Error(result.error?.message ?? 'the listing was refused')
    }
    return result.value
  }

  const nameProject = async (projectId: WorkspaceId | undefined, title: string): Promise<void> => {
    const named = projectId === undefined
      ? await ctx.workspaces.create({ title })
      : await ctx.workspaces.rename(projectId, title)
    const id = named.workspaceId
    target.set({ workspaceId: id })
    // The requested walk is answered the moment the project exists. Clearing it here rather than
    // when the walk finishes is what lets the *rest* of the walk be described by the project's own
    // record: a request still standing would keep suppressing the resolution, so steps 2 onward
    // would render against no project at all.
    request.set(EMPTY_REQUEST)
    // `completeStep` starts from the empty record when there is none, and merges rather than
    // replaces: reaching step 1 again from a walk already past it must not clear the answers
    // the later steps recorded.
    store.set({ ...store.getSnapshot(), [id]: completeStep(store.getSnapshot()[id], 'project', { projectTitle: title }) })
  }

  const addRepositoryRoot = async (workspaceId: WorkspaceId, path: string): Promise<void> => {
    await ctx.workspaces.addRoot(workspaceId, path)
  }

  const removeRepositoryRoot = async (workspaceId: WorkspaceId, path: string): Promise<void> => {
    await ctx.workspaces.removeRoot(workspaceId, path)
  }

  const loadDocuments = async (
    workspaceId: string,
    extraDirectories: readonly string[],
  ): Promise<YxspecDocumentListing> => {
    const namespace = ctx.remote.yxspec
    if (namespace === undefined) return EMPTY_LISTING
    const result = await namespace.documents(workspaceId, [...extraDirectories]) as RemoteOutcome<YxspecDocumentListing>
    return result.ok ? result.value ?? EMPTY_LISTING : EMPTY_LISTING
  }

  const loadServers = async (workspaceId: string): Promise<YxspecRemoteServerView[]> => {
    const namespace = ctx.remote.yxspecRemote
    if (namespace === undefined) return []
    const result = await namespace.servers(workspaceId) as RemoteOutcome<YxspecRemoteServerView[]>
    return result.ok ? result.value ?? [] : []
  }

  /**
   * Declare one build server for a project.
   *
   * A refused declaration throws rather than answering with nothing: the wizard's form has to
   * tell the operator which field the host rejected, and an empty answer is indistinguishable
   * from a write that never happened. The host owns every rule the message can report —
   * required, absolute, positive — so this is a carrier, not a second validator.
   * @param workspaceId - the project the declaration belongs to.
   * @param draft - the declaration the operator submitted.
   * @returns the stored declaration as the list renders it.
   */
  const declareServer = async (
    workspaceId: string,
    draft: YxspecRemoteServerDraft,
  ): Promise<YxspecRemoteServerView> => {
    const namespace = ctx.remote.yxspecRemote
    if (namespace === undefined) throw new Error('the build-server namespace is not mounted')
    const result = await namespace.declareServer(workspaceId, draft) as RemoteOutcome<YxspecRemoteServerView>
    if (!result.ok || result.value === undefined) {
      throw new Error(result.error?.message ?? 'the declaration was refused')
    }
    return result.value
  }

  /**
   * The walk is finished: open the project it created.
   *
   * The gate governs a *blank home* and nothing else, so every step of the walk runs with no
   * Session selected — and a project cannot be attached to one until it has a repository root,
   * which step 2 is where the walk supplies. Finishing is therefore the first moment the walk's
   * project is a place the operator can actually work, and opening it is what makes the five
   * steps add up to a created project rather than to a form that closed.
   *
   * Failure is not reported here: the selection stays blank and the walk's own record is complete,
   * so the gate opens and the sidebar lists the project. Raising a notice would want a locale seat
   * this registration does not own.
   * @param workspaceId - the project the finished walk created.
   */
  const finishOnboarding = (workspaceId: WorkspaceId): void => {
    // `startSession` rather than `openWorkspace`: it is the surface's own "show me this project's
    // blank work" action, it resolves the reusable blank the host already has instead of minting
    // a second one on a re-walk, and it is synchronous — a rejected create is reported through
    // the Workspace notice channel, which the caller here has no better way to do.
    ctx.uiWorkspace.startSession(workspaceId, { clearPreviousDraft: false })
  }

  const injected = (): OnboardingWizardInjected => ({
    hooks: {
      // Retained as a source, not read through a closure: the renderer binds it to a selector
      // hook, so the wizard re-renders when a step is saved. A snapshot read captured in a
      // callback would leave the gate deciding from a value React was never told changed.
      onboardingProgress: store,
      onboardingTarget: target,
      onboardingRequest: request,
    },
    saveProgress,
    loadDocuments,
    loadServers,
    declareServer,
    probeServer,
    browseServer,
    nameProject,
    finishOnboarding,
    addRepositoryRoot,
    removeRepositoryRoot,
    pickDirectory: async () => {
      const result = await ctx.remote.directoryPicker.pick()
      if (!result.ok) throw new Error(result.error.message)
      return result.value ?? undefined
    },
  })

  ctx.slots.inject('conversation.hero.frame', () => ctx.slots.register({
    name: 'conversation.hero.frame',
    id: 'yxspec-onboarding',
    // Outermost layer: the gate decides whether the scroll body exists at all, so it must wrap
    // the decorative layers rather than sit inside one of them.
    order: -100,
    // Declaring the namespace is what puts the `t` seat on the composed props; a HOC layer
    // renders copy like any other entry, so the seat is part of its contract.
    locale: NS,
    inject: injected,
  }, OnboardingWizard))
}
