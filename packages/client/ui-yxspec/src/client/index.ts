/**
 * YXSpec process panel, browser half: the session panel's ASPICE stage section, and the
 * onboarding gate that stands in front of a blank Conversation.
 *
 * The section reads `ctx.remote.yxspec`, the Remote namespace `yxspec-api` owns. It renders
 * the stage list but offers no control to advance a step: advancing is a tool call, which
 * must travel through the host gate — a UI control that moved the pointer directly would be
 * a second, unguarded path through the process, which is exactly what this migration exists
 * to remove.
 *
 * The gate is the same principle applied to the step before any of that: the process only
 * means something against a chosen specification, a named project, its repositories, and (when
 * the deployment builds remotely) a declared server, so the Conversation does not open until
 * the operator has said what all four are. It registers as a `conversation.hero.frame` HOC
 * layer and simply declines to render that layer's children — the scroll body holding the
 * composer seat — until the project is onboarded. Declining to render is the gate: there is no
 * disabled input box to re-enable, and no separate code path that could disagree with this one.
 *
 * Both surfaces read their Remotes defensively. A missing namespace (host plugin absent) and
 * a refused call both render as an unavailable-service notice, so a partially deployed host
 * shows a quiet panel rather than a broken one.
 * @module @deepseek-ai/dsh-client-ui-yxspec
 */

